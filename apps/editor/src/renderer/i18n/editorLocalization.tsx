export const EDITOR_LANGUAGES = ['zh-CN', 'en-US'] as const satisfies readonly EditorLanguage[];
export { DEFAULT_EDITOR_LANGUAGE };
export type { EditorLanguage };

export const EDITOR_LABELS: Readonly<Record<EditorLanguage, EditorLabels>> = {
  'zh-CN': zhCN,
  'en-US': enUS,
};

export function normalizeEditorLanguage(value: unknown): EditorLanguage {
  return value === 'en-US' ? 'en-US' : DEFAULT_EDITOR_LANGUAGE;
}

export function getEditorLabels(language: EditorLanguage): EditorLabels {
  return EDITOR_LABELS[language];
}

type EditorI18nValue = {
  language: EditorLanguage;
  labels: EditorLabels;
};

const defaultValue: EditorI18nValue = {
  language: DEFAULT_EDITOR_LANGUAGE,
  labels: getEditorLabels(DEFAULT_EDITOR_LANGUAGE),
};

const EditorI18nContext = createContext<EditorI18nValue>(defaultValue);

export function EditorI18nProvider({
  language,
  children,
}: {
  language: EditorLanguage;
  children: ReactNode;
}) {
  const value = useMemo<EditorI18nValue>(
    () => ({ language, labels: getEditorLabels(language) }),
    [language],
  );
  return (
    <EditorI18nContext.Provider value={value}>
      {children}
    </EditorI18nContext.Provider>
  );
}

export function useEditorI18n(): EditorI18nValue {
  return useContext(EditorI18nContext);
}

export function useEditorLabels(): EditorLabels {
  return useEditorI18n().labels;
}

export function useEditorLanguage(): EditorLanguage {
  return useEditorI18n().language;
}
